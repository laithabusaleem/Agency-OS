import { getFixture } from "@/delivery/fixtures";
import type { DeliveryTool } from "@/delivery/types";

/**
 * Renders static HTML from allowlisted templates + brief answers.
 * Does NOT evaluate or execute any model-supplied code.
 */
export const renderStaticHtmlTool: DeliveryTool = {
  id: "render_static_html",
  async execute(ctx, params) {
    const fixture = getFixture("website_base");
    const businessName = String(ctx.brief.businessName ?? "Business");
    const primaryGoal = String(ctx.brief.primaryGoal ?? "Learn more");
    const brandTone = String(ctx.brief.brandTone ?? "professional");
    const css = String(fixture.stylesheet ?? "");

    const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>${escapeHtml(businessName)}</title>
  <link rel="stylesheet" href="./styles.css" />
</head>
<body data-tone="${escapeHtml(brandTone)}">
  <header>
    <p class="brand">${escapeHtml(businessName)}</p>
    <h1>${escapeHtml(businessName)}</h1>
    <p>A ${escapeHtml(brandTone)} presence focused on: ${escapeHtml(primaryGoal)}</p>
    <a class="cta" href="#cta" id="primary-cta">${escapeHtml(primaryGoal)}</a>
  </header>
  <main>
    <section id="offer">
      <h2>What we offer</h2>
      <p>Scoped static deliverable generated in an isolated workspace (mode=${escapeHtml(ctx.mode)}).</p>
    </section>
    <section id="cta">
      <h2>Next step</h2>
      <p><a href="./styles.css">Stylesheet</a></p>
    </section>
  </main>
  <footer>
    <p>Generated by Agency OS delivery agent — no host code execution.</p>
  </footer>
</body>
</html>`;

    return {
      ok: true,
      artifacts: [
        {
          key: String(params.outputKey ?? "site_index"),
          relativePath: "site/index.html",
          contentType: "text/html",
          content: html,
          metadata: { renderer: "allowlisted_static", brandTone },
        },
        {
          key: "site_styles",
          relativePath: "site/styles.css",
          contentType: "text/css",
          content: css,
        },
      ],
      data: { sections: fixture.sections },
    };
  },
};

function escapeHtml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}
